create table if not exists people (
  id integer generated by default as identity primary key,
  slug text not null unique,
  name text not null,
  color text not null default '#2f6fed',
  created_at timestamp not null default now()
);

create table if not exists accounts (
  id integer generated by default as identity primary key,
  person_id integer not null references people(id) on delete cascade,
  name text not null,
  type text not null,
  kind text not null check (kind in ('debit', 'credit')),
  balance integer not null default 0,
  is_default boolean not null default false,
  credit_limit integer,
  cutoff_day integer,
  due_day integer,
  created_at timestamp not null default now()
);

create table if not exists expenses (
  id integer generated by default as identity primary key,
  title text not null,
  total_amount integer not null,
  date date not null,
  paid_by_person_id integer not null references people(id),
  account_id integer references accounts(id) on delete set null,
  split_type text not null check (split_type in ('equal', 'items', 'full_daniel', 'full_ana')),
  share_ana integer not null default 0,
  share_daniel integer not null default 0,
  surcharge_amount integer not null default 0,
  surcharge_split_type text not null default 'equal',
  notes text,
  receipt_image_url text,
  source text not null default 'manual',
  created_at timestamp not null default now()
);

create table if not exists expense_items (
  id integer generated by default as identity primary key,
  expense_id integer not null references expenses(id) on delete cascade,
  description text not null,
  amount integer not null,
  assigned_to text not null check (assigned_to in ('ana', 'daniel', 'equal'))
);

create table if not exists settlements (
  id integer generated by default as identity primary key,
  from_person_id integer not null references people(id),
  to_person_id integer not null references people(id),
  amount integer not null,
  date date not null,
  note text,
  from_account_id integer references accounts(id) on delete set null,
  to_account_id integer references accounts(id) on delete set null,
  created_at timestamp not null default now()
);

create table if not exists account_transactions (
  id integer generated by default as identity primary key,
  account_id integer not null references accounts(id) on delete cascade,
  type text not null,
  amount integer not null,
  description text,
  date date not null,
  related_expense_id integer references expenses(id) on delete set null,
  transfer_group_id text,
  created_at timestamp not null default now()
);

create table if not exists receipt_drafts (
  id integer generated by default as identity primary key,
  image_url text,
  merchant_guess text,
  items jsonb not null,
  ai_note text,
  status text not null default 'pending',
  created_at timestamp not null default now()
);

create table if not exists receipt_blobs (
  id integer generated by default as identity primary key,
  content_type text not null,
  data bytea not null,
  created_at timestamp not null default now()
);

create table if not exists goals (
  id integer generated by default as identity primary key,
  name text not null,
  target_amount integer not null check (target_amount > 0),
  frequency text not null default 'una_vez' check (frequency in ('una_vez', 'semanal', 'mensual', 'anual')),
  deadline date,
  current_saved integer not null default 0,
  notes text,
  created_at timestamp not null default now()
);

create index if not exists idx_expenses_date on expenses(date desc, id desc);
create index if not exists idx_expense_items_expense on expense_items(expense_id);
create index if not exists idx_account_tx_account on account_transactions(account_id);
create index if not exists idx_account_tx_date on account_transactions(date desc, id desc);

